export const productBySlug = (slug: string) => products.find((p) => p.slug === slug);

export const priceBounds: [number, number] = [
  Math.min(...products.map((p) => p.price)),
  Math.max(...products.map((p) => p.price)),
];

export const relatedProducts = (product: Product, count = 4) => {
  const sameCat = products.filter((p) => p.slug !== product.slug && p.category === product.category);
  const others = products.filter((p) => p.slug !== product.slug && p.category !== product.category);
  return [...sameCat, ...others].slice(0, count);
};

